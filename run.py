#!/usr/bin/env python3
"""InboxKit GTM workflow CLI.

  python3 run.py build      --icp config/icp.json --people data/raw/clay_people_export.csv \
                            --companies data/raw/clay_companies_export.csv --out out/agencies
  python3 run.py clay-query --icp config/icp.json
  python3 run.py lint-copy  copy/*.md
  python3 run.py check-out  out/agencies
  python3 run.py render     out/agencies --n 10    # merged drafts for review, India rows first

Nothing here sends a message. The output is CSV for a human to import as drafts.
"""
import argparse
import csv
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from gtm import icp as icp_mod  # noqa: E402
from gtm import lint, pipeline  # noqa: E402
from gtm import render as render_mod  # noqa: E402
from gtm.personalize import lint_line  # noqa: E402


def cmd_build(a):
    icp = icp_mod.load_icp(a.icp)
    res = pipeline.build(
        icp, a.people, a.companies, a.suppression, a.out, a.dns_cache,
        offline=a.offline, limit=a.limit, source_label=a.source_label)
    print(res["report"])
    print("Wrote %s/lead_list.csv (%d rows), sequencer_import.csv, rejects.csv (%d rows), report.md"
          % (a.out, len(res["accepted"]), len(res["rejects"])))
    return 0


def cmd_clay_query(a):
    companies, people = icp_mod.clay_queries(icp_mod.load_icp(a.icp))
    print("# search-companies dslQuery\n" + companies + "\n")
    print("# search-contacts dslQuery (pass up to 10 company domains per call)\n" + people)
    return 0


def cmd_lint_copy(a):
    claims = open(os.path.join(HERE, "claims.md")).read()
    paths = [p for pat in a.paths for p in glob.glob(pat)]
    errors = []
    for p in paths:
        errors += lint.lint_text(open(p).read(), claims, path=os.path.relpath(p))
    for e in errors:
        print("FAIL " + e)
    print("%d file(s) checked, %d problem(s)" % (len(paths), len(errors)))
    return 1 if errors else 0


def cmd_check_out(a):
    path = os.path.join(a.out, "sequencer_import.csv")
    rows = list(csv.DictReader(open(path)))
    bad = []
    seen = set()
    for r in rows:
        if r["email"] in seen:
            bad.append("duplicate email %s" % r["email"])
        seen.add(r["email"])
        for p in lint_line(r["first_line"]):
            bad.append("%s: first line %s" % (r["email"], p))
    for b in bad:
        print("FAIL " + b)
    print("%d rows checked, %d problem(s)" % (len(rows), len(bad)))
    return 1 if bad else 0


def cmd_render(a):
    rows = list(csv.DictReader(open(os.path.join(a.out, "sequencer_import.csv"))))
    basis = {r["email"]: r["line_basis"] for r in csv.DictReader(open(os.path.join(a.out, "lead_list.csv")))}
    for r in rows:
        r["line_basis"] = basis.get(r["email"], "")
    seqs = {k: render_mod.parse_sequence(open(os.path.join(HERE, "copy", "sequence_%s.md" % k)).read())
            for k in ("india", "global")}
    sample = render_mod.pick_sample(rows, a.n)
    md, problems = render_mod.render(sample, seqs, a.sender)
    header = ("# Sample drafts (generated by `run.py render`, not sent)\n\n"
              "%d rows from `%s`, India rows first, one per company, varied signal-line basis. "
              "Step 1 alternates variants A and B.\n\n" % (len(sample), a.out))
    path = os.path.join(a.out, "drafts_sample.md")
    with open(path, "w") as f:
        f.write(header + md)
    for p in problems:
        print("FAIL " + p)
    print("Wrote %s (%d drafts, %d problem(s))" % (path, len(sample), len(problems)))
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("build", help="ICP filter, dedupe, suppress, email checks, first lines, export")
    b.add_argument("--icp", default="config/icp.json")
    b.add_argument("--people", required=True)
    b.add_argument("--companies", help="company export joined on domain (optional)")
    b.add_argument("--suppression", default="config/suppression.csv")
    b.add_argument("--out", default="out/run")
    b.add_argument("--dns-cache", default="data/cache/dns.json")
    b.add_argument("--offline", action="store_true", help="use the DNS cache only, no network")
    b.add_argument("--limit", type=int)
    b.add_argument("--source-label", default="Clay search export")
    b.set_defaults(fn=cmd_build)

    q = sub.add_parser("clay-query", help="print the Clay Search DSL for an ICP")
    q.add_argument("--icp", default="config/icp.json")
    q.set_defaults(fn=cmd_clay_query)

    l = sub.add_parser("lint-copy", help="check copy against the brief's rules")
    l.add_argument("paths", nargs="+")
    l.set_defaults(fn=cmd_lint_copy)

    c = sub.add_parser("check-out", help="re-check a built list before import")
    c.add_argument("out")
    c.set_defaults(fn=cmd_check_out)

    r = sub.add_parser("render", help="merge copy with built rows into review drafts")
    r.add_argument("out")
    r.add_argument("--n", type=int, default=10)
    r.add_argument("--sender", default="[your name]")
    r.set_defaults(fn=cmd_render)

    a = ap.parse_args()
    sys.exit(a.fn(a))


if __name__ == "__main__":
    main()
